export function statusLabel(value: string | null | undefined, context: StatusContext = 'generic'): string {
  if (!value) return c('未报告', 'Not reported')
  const scoped = contextual[context]
  const pair = scoped && Object.hasOwn(scoped, value) ? scoped[value] : Object.hasOwn(statusLabels, value) ? statusLabels[value] : undefined
  return pair ? c(...pair) : c('未识别状态', 'Unknown status')
}
export function statusTone(value: string): StatusTone {
  if (['COMPARABLE','FORMAL','QUALIFIED_FOR_SUITE','READY','capability_pass','VERIFIED_PASS','PASS','PASSED','SET','SUPPORTED','COMPATIBLE','VERIFIED'].includes(value)) return 'good'
  if (['NOT_QUALIFIED','FAILED_INFRA','TIMEOUT','BLOCKED','failed','failed_subject','failed_infra','failed_verifier','capability_fail','infra_failure','VERIFIED_FAIL','FAIL','FAILED','CORRUPT','UNAVAILABLE / ERROR','QUOTA_EXHAUSTED','UNSUPPORTED','INCOMPATIBLE'].includes(value)) return 'bad'
  if (['NOT_AUTHORIZED','INTERRUPTED','NOT_READY','NOT_COMPARABLE','PARTIALLY_COMPARABLE','INFORMAL','HYPOTHESIS','MISSING','NOT_CONFIGURED','NOT_RUN','NOT_VERIFIED','WARNING','READY_WITH_WARNINGS','PARTIALLY_SUPPORTED','CREDENTIAL MISSING','RUNTIME UNVERIFIED'].includes(value)) return 'warn'
  return 'neutral'
}
// Display only known metadata enums; identity strings are rendered by identity components.
export function metadataLabel(value: string | null | undefined): string {
  if (!value) return statusLabel('NOT_REPORTED')
  const pair = Object.hasOwn(metadataLabels, value) ? metadataLabels[value] : undefined
  return pair ? c(...pair) : statusLabel(value)
}
